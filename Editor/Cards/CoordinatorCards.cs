using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace Coordinator.Editor
{
    public static class CoordinatorCards
    {
        public const string CardsFolder = "Cards";
        public const string TaskCardFile = "README.md";
        private const string Banner = "<!-- Generated by Coordinator. Do not edit; change the JSON and regenerate. -->";
        private static readonly Regex VariableUse = new(@"\$\{([^}]*)\}", RegexOptions.Compiled);

        public static string CardPath(string taskId, string assignmentId) =>
            $"{CoordinatorPaths.RepositoryTaskFolder(taskId)}/{CardsFolder}/{assignmentId}.md";

        public static int WriteAll(CoordinatorWorkspace workspace)
        {
            var written = 0;
            foreach (var data in workspace.Tasks)
            {
                var folder = Path.Combine(workspace.Paths.TaskFolder(data.FolderId), CardsFolder);
                Directory.CreateDirectory(folder);
                var expected = new Dictionary<string, string>(StringComparer.Ordinal)
                {
                    [TaskCardFile] = Task(workspace.Project, data)
                };
                foreach (var assignment in data.Assignments)
                    expected[assignment.id + ".md"] = Assignment(workspace.Project, data, assignment, workspace.Architector);
                foreach (var stale in Directory.GetFiles(folder, "*.md").Where(path => !expected.ContainsKey(Path.GetFileName(path))))
                    File.Delete(stale);
                foreach (var pair in expected)
                {
                    var path = Path.Combine(folder, pair.Key);
                    if (File.Exists(path) && File.ReadAllText(path) == pair.Value)
                        continue;
                    File.WriteAllText(path, pair.Value, new UTF8Encoding(false));
                    written++;
                }
            }
            return written;
        }

        public static string Task(CoordinatorProjectRecord project, CoordinatorTaskData data)
        {
            var task = data.Task;
            var text = new Text();
            text.Line(Banner).Line($"# {task.title}").Blank();
            text.Line($"Task `{task.id}`. Lead: {task.lead}. Target branch `{task.targetBranch}`"
                      + (string.IsNullOrEmpty(task.integrationBranch) ? "" : $", integration branch `{task.integrationBranch}`")
                      + $". Base `{task.baseRevision.branch}`" + (string.IsNullOrEmpty(task.baseRevision.commit) ? "." : $" (`{Short(task.baseRevision.commit)}`)."));
            text.Line(task.approval == null ? "Not approved yet: assignments do not start." : $"Approved by {task.approval.by} on {task.approval.date}.");
            if (task.cancelled != null)
                text.Line($"Cancelled by {task.cancelled.by} on {task.cancelled.date}: {task.cancelled.reason}");
            if (task.sources.Count > 0)
            {
                text.Blank().Line("## Sources").Blank();
                foreach (var source in task.sources)
                    text.Line("- " + Document(source));
            }
            if (task.decisions.Count > 0)
            {
                text.Blank().Line("## Decisions").Blank();
                foreach (var decision in task.decisions)
                    text.Line($"- **{decision.id}** ({decision.state}, {decision.owner}): {decision.question}"
                              + (decision.state == CoordinatorDecisionStates.Decided ? $" Answer: {decision.answer}" : "") + Record(decision.record));
            }
            text.Blank().Line("## Assignments").Blank().Line("| Assignment | Executor | Environment | Branch | Write zone |").Line("| --- | --- | --- | --- | --- |");
            foreach (var assignment in data.Assignments)
                text.Line($"| [{assignment.title}]({assignment.id}.md) | {assignment.executor?.handle ?? "-"} | {assignment.executor?.environment} | `{assignment.executor?.branch}` | {string.Join(", ", assignment.writeZone.Select(pattern => $"`{pattern}`"))} |");
            if (task.integration != null)
            {
                text.Blank().Line("## Integration").Blank();
                if (task.integration.dependsOn.decisions.Count > 0)
                    text.Line("Waits for decisions: " + string.Join(", ", task.integration.dependsOn.decisions) + ".").Blank();
                var step = 1;
                foreach (var routeStep in task.integration.route)
                    text.Line($"{step++}. {routeStep.text}");
                if (task.integration.acceptance.Count > 0)
                {
                    text.Blank().Line("Acceptance:").Blank();
                    foreach (var item in task.integration.acceptance)
                        text.Line($"- **{item.id}**: {item.text}");
                }
                if (!string.IsNullOrEmpty(task.integration.limits))
                    text.Blank().Line(task.integration.limits);
            }
            return text.ToString();
        }

        public static string Assignment(
            CoordinatorProjectRecord project,
            CoordinatorTaskData data,
            CoordinatorAssignmentRecord assignment,
            CoordinatorArchitector architector = null)
        {
            var task = data.Task;
            var text = new Text();
            var baseRevision = CoordinatorScope.Base(task);
            text.Line(Banner).Line($"# {assignment.title}").Blank();
            var environment = assignment.executor?.environment;
            text.Line($"Task: {task.title} (`{task.id}`). Lead: {task.lead}. Disciplines: {string.Join(", ", assignment.disciplines)}.").Blank();
            text.Line(Environment(environment)).Blank();
            text.Line($"Work in branch `{assignment.executor?.branch}`, started from `{task.baseRevision.branch}`"
                      + (string.IsNullOrEmpty(task.baseRevision.commit) ? "." : $" (`{Short(task.baseRevision.commit)}`).")
                      + " Read the current version of this card from the lead's branch, not from your checkout:").Blank();
            text.Code($"git show {task.targetBranch}:{CardPath(task.id, assignment.id)}");
            if (assignment.cancelled != null)
                text.Blank().Line($"**Cancelled** by {assignment.cancelled.by} on {assignment.cancelled.date}: {assignment.cancelled.reason}");

            text.Blank().Line("## Goal").Blank().Line(assignment.goal);

            if (assignment.readFirst.Count > 0)
            {
                text.Blank().Line("## Read First").Blank();
                var index = 1;
                foreach (var document in assignment.readFirst)
                    text.Line($"{index++}. {Document(document)}");
            }
            if (assignment.layers.Count > 0)
                text.Blank().Line("Architecture: " + string.Join("; ", assignment.layers.Select(layer => $"`{layer.path}` ({layer.role})")) + ". The lead authors and links the graph.");

            if (assignment.inputs.Count > 0)
            {
                text.Blank().Line("## Inputs").Blank().Line("| Input | Kind | Use |").Line("| --- | --- | --- |");
                foreach (var input in assignment.inputs)
                    text.Line($"| {Input(input)} | {input.kind} | {input.use ?? ""} |");
            }

            text.Blank().Line("## Decisions That Apply").Blank();
            var decisionIds = assignment.dependsOn.decisions
                .Concat(assignment.inputs.Where(input => input.kind == CoordinatorInputKinds.Decision).Select(input => input.decision))
                .Where(id => id != null).Distinct().ToArray();
            var decisions = task.decisions.Where(decision => decisionIds.Contains(decision.id)).ToArray();
            if (decisions.Length == 0)
                text.Line("None of this task's decisions apply to this assignment.");
            foreach (var decision in decisions)
                text.Line(decision.state == CoordinatorDecisionStates.Decided
                    ? $"- **{decision.id}**: {decision.answer}{Record(decision.record)}"
                    : $"- **{decision.id}** is open: {decision.question} This assignment waits for it.");
            var otherOpen = task.decisions.Where(decision => decision.state == CoordinatorDecisionStates.Open && !decisionIds.Contains(decision.id)).ToArray();
            if (otherOpen.Length > 0)
                text.Blank().Line("Also open in the task, not blocking this assignment: " + string.Join(", ", otherOpen.Select(decision => $"`{decision.id}`")) + ". Do not settle them.");

            if (assignment.dependsOn.outputs.Count > 0)
                text.Blank().Line("Waits for outputs: " + string.Join(", ", assignment.dependsOn.outputs.Select(output => $"`{output.assignment}/{output.output}`")) + ".");

            if (assignment.outputs.Count > 0)
            {
                text.Blank().Line("## Outputs").Blank();
                foreach (var output in assignment.outputs)
                    text.Line($"- `{output.id}` ({output.kind}): {output.summary ?? string.Join(", ", output.paths)}");
            }

            text.Blank().Line("## Write Zone").Blank().Line("You may change only:").Blank();
            foreach (var pattern in CoordinatorScope.AuthoredZone(assignment, architector))
                text.Line($"- `{pattern}`");
            text.Line($"- `{CoordinatorPaths.RepositoryDeliveryPath(task.id, assignment.id)}` (your delivery)");
            var reserved = CoordinatorScope.Reserved(project, task);
            if (reserved.Count > 0)
                text.Blank().Line("Reserved paths stay unchanged even inside the zone: " + string.Join(", ", reserved.Select(pattern => $"`{pattern}`")) + ".");

            if (assignment.route.Count > 0)
            {
                text.Blank().Line("## Route").Blank();
                var step = 1;
                foreach (var routeStep in assignment.route)
                {
                    var checks = (routeStep.checks ?? new List<string>()).Concat(routeStep.check == null ? Array.Empty<string>() : new[] { routeStep.check }).ToArray();
                    text.Line($"{step++}. {routeStep.text}" + (checks.Length == 0 ? "" : " Check: " + string.Join(", ", checks.Select(check => $"`{check}`")) + "."));
                }
            }

            var forbidden = assignment.forbidden.Select(item => item.text).Concat(task.forbidden.Select(item => item.text + " (task)")).ToArray();
            var rules = project.rules.Where(rule => CoordinatorEnvironments.Applies(rule.environments, environment)).ToArray();
            if (forbidden.Length > 0 || rules.Length > 0)
            {
                text.Blank().Line("## Forbidden").Blank();
                foreach (var item in forbidden)
                    text.Line("- " + item);
                if (rules.Length > 0)
                    text.Blank().Line("Project rules: " + string.Join(" ", rules.Select(rule => rule.text)));
            }

            text.Blank().Line("## Acceptance").Blank().Line("You run:").Blank();
            var variables = new SortedSet<string>(StringComparer.Ordinal);
            var listedChecks = new HashSet<string>(StringComparer.Ordinal);
            foreach (var item in assignment.acceptance.Where(item => item.runBy == CoordinatorRunBy.Executor))
            {
                if (!string.IsNullOrEmpty(item.command))
                    text.Line($"- **{item.id}**: `{Command(item.command, variables)}`. {item.text}");
                else if (!string.IsNullOrEmpty(item.testFilter))
                    text.Line($"- **{item.id}**: tests `{item.testFilter}`. {item.text}");
                foreach (var checkId in (item.checks ?? new List<string>()).Concat(item.check == null ? Array.Empty<string>() : new[] { item.check }))
                {
                    if (!listedChecks.Add(checkId))
                        continue;
                    var check = project.checks.FirstOrDefault(candidate => candidate.id == checkId);
                    if (check == null)
                        continue;
                    text.Line(check.generated == "scope"
                        ? $"- **{check.id}**: the commands below. Each must print nothing."
                        : $"- **{check.id}**: `{Command(check.command, variables)}`" + (string.IsNullOrEmpty(check.limits) ? "" : $" {check.limits}"));
                }
            }
            foreach (var variable in variables)
            {
                var description = project.variables.FirstOrDefault(candidate => candidate.id == variable)?.description ?? string.Empty;
                text.Line($"- `<{variable}>`: {description} Ask the lead for its value on your machine.");
            }
            if (listedChecks.Any(id => project.checks.Any(check => check.id == id && check.generated == "scope")))
                text.Blank().Code(string.Join("\n", CoordinatorScope.Commands(project, task, assignment, architector)));

            var leadItems = assignment.acceptance.Where(item => item.runBy == CoordinatorRunBy.Lead).ToArray();
            if (leadItems.Length > 0)
            {
                text.Blank().Line("The lead runs at review:").Blank();
                foreach (var item in leadItems)
                    text.Line($"- **{item.id}**: {item.text}" + (string.IsNullOrEmpty(item.testFilter) ? "" : $" Tests `{item.testFilter}`: compile them, do not report them as executed."));
            }

            text.Blank().Line("## Delivery").Blank();
            text.Line($"Write `{CoordinatorPaths.RepositoryDeliveryPath(task.id, assignment.id)}` in the documented format: set `state` to `inProgress` when you start and `delivered` in your final commit. "
                      + "Report the checks you ran with exit codes and results, the public contracts, the open integration requirements, what stays unverified, "
                      + "and in `judgments` every choice this card did not settle, with its reason. Do not log your actions. Do not write the commit SHA: Coordinator reads it from git.");
            text.Blank().Line("## Hand-In And Merge").Blank();
            text.Line("1. Your operator, the person who runs you, checks the result and hands this card in to the lead. Pushing and pull requests are the operator's act: never push.");
            text.Line("2. The lead reviews the card and accepts or returns it. A returned card comes back with findings; fix them in your branch and deliver again.");
            text.Line($"3. When the lead has accepted it, merge your branch into the task branch `{task.integrationBranch}`. Never merge into `{task.targetBranch}`: only the lead's approval of the whole task branch lets it in.");
            text.Blank().Code($"git switch {task.integrationBranch}\ngit merge --no-ff {assignment.executor?.branch}");
            return text.ToString();
        }

        private static string Environment(string environment) => environment switch
        {
            CoordinatorEnvironments.Worktree => "Executor environment: `worktree`, your own git worktree without Unity. Checks that need Unity are run by the lead.",
            CoordinatorEnvironments.Editor => "Executor environment: `editor`, your operator's checkout with the Unity Editor open. You work through the Editor's tools.",
            _ => $"Executor environment: `{environment}`, not declared correctly."
        };

        private static string Command(string command, ISet<string> variables)
        {
            return VariableUse.Replace(command, match =>
            {
                variables.Add(match.Groups[1].Value);
                return $"<{match.Groups[1].Value}>";
            });
        }

        private static string Document(CoordinatorDocumentRef document)
        {
            var line = $"`{document.path}`";
            if (document.sections?.Count > 0)
                line += " " + string.Join(", ", document.sections.Select(section => "§" + section));
            if (document.requirements?.Count > 0)
                line += ". Requirements: " + string.Join(", ", document.requirements);
            if (!string.IsNullOrEmpty(document.note))
                line += ". " + document.note;
            return line;
        }

        private static string Input(CoordinatorInputRecord input)
        {
            return input.kind switch
            {
                CoordinatorInputKinds.Source => $"`{input.path}`",
                CoordinatorInputKinds.Output => $"`{input.assignment}/{input.output}`",
                CoordinatorInputKinds.Decision => $"decision `{input.decision}`",
                _ => input.text + (input.supplied == true ? " (supplied)" : " (not supplied yet)")
            };
        }

        private static string Record(CoordinatorRecordLink record)
        {
            if (record == null)
                return string.Empty;
            if (!string.IsNullOrEmpty(record.layer))
                return $" Recorded in layer `{record.layer}`.";
            return string.IsNullOrEmpty(record.path) ? string.Empty
                : $" Recorded in `{record.path}`" + (string.IsNullOrEmpty(record.section) ? "." : $", {record.section}.");
        }

        private static string Short(string commit) => commit.Length > 8 ? commit.Substring(0, 8) : commit;

        private sealed class Text
        {
            private readonly StringBuilder builder = new();

            public Text Line(string line)
            {
                builder.Append(line).Append('\n');
                return this;
            }

            public Text Blank() => Line(string.Empty);

            public Text Code(string code) => Line("```bash").Line(code).Line("```");

            public override string ToString() => builder.ToString();
        }
    }
}
