using System.IO;
using NUnit.Framework;

namespace Coordinator.Editor.Tests
{
    public sealed class CoordinatorCardsTests
    {
        [Test]
        public void TheCardCarriesZoneDecisionsChecksAndScopeCommands()
        {
            using var project = new CoordinatorTestProject();
            project.Assignments[0].dependsOn.decisions.Add("door-authority");
            var workspace = project.Save();
            var data = workspace.FindTask("doors");

            var card = CoordinatorCards.Assignment(workspace.Project, data, data.Assignments[0]);

            Assert.That(card, Does.StartWith("<!-- Generated by Coordinator."));
            Assert.That(card, Does.Contain("- `Assets/Scripts/Doors/**`"));
            Assert.That(card, Does.Contain("**door-authority**: The host."));
            Assert.That(card, Does.Contain("Also open in the task, not blocking this assignment: `light-timing`"));
            Assert.That(card, Does.Contain("`compile <snapshot>`").And.Contain("`<snapshot>`: Compiler snapshot"));
            Assert.That(card, Does.Contain("git diff --no-renames --name-only abc1234 -- . ':(exclude,glob)Assets/Scripts/Doors/**'"));
            Assert.That(card, Does.Contain("`judgments`").And.Contain("Do not log your actions"));
            Assert.That(card, Does.Contain("git show develop:Coordinator/Tasks/doors/Cards/door-rules.md"));
            Assert.That(card, Does.Not.Contain("\r"));
        }

        [Test]
        public void WritingCardsIsIdempotentAndRemovesStaleOnes()
        {
            using var project = new CoordinatorTestProject();
            var workspace = project.Save();
            var folder = Path.Combine(project.Paths.TaskFolder("doors"), CoordinatorCards.CardsFolder);

            Assert.That(CoordinatorCards.WriteAll(workspace), Is.EqualTo(3));
            File.WriteAllText(Path.Combine(folder, "gone.md"), "stale");
            Assert.That(CoordinatorCards.WriteAll(workspace), Is.Zero);
            Assert.That(File.Exists(Path.Combine(folder, "gone.md")), Is.False);
            Assert.That(File.ReadAllText(Path.Combine(folder, CoordinatorCards.TaskCardFile)), Does.Contain("[door-rules](door-rules.md)"));
        }
    }
}
